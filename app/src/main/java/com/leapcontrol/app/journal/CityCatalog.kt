/**
 * 经纬度 → 画布坐标（等距圆柱投影，只用于「把城市摆在大概的位置」）。
 *
 * 刻意不套用任何官方投影参数：足迹图不是地图，只是把这些城市点铺开，
 * 用哪套投影都改变不了「点与点的相对位置」，反而越简单越不容易出错。
 */
object CityProjection {
    const val MIN_LON = 73.0f
    const val MAX_LON = 136.0f
    const val MIN_LAT = 17.0f
    const val MAX_LAT = 54.0f

    /** 0~1；超出范围的城市（理论上没有）夹进边界，不让点跑到画布外。 */
    fun x(lon: Float): Float = ((lon - MIN_LON) / (MAX_LON - MIN_LON)).coerceIn(0f, 1f)

    fun y(lat: Float): Float = ((MAX_LAT - lat) / (MAX_LAT - MIN_LAT)).coerceIn(0f, 1f)
}
