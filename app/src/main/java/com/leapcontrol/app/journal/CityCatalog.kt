    /** 按省份分组（顺序与 [ALL] 一致，不重新排序）。 */
    val BY_PROVINCE: List<Pair<String, List<City>>> = run {
        val order = mutableListOf<String>()
        val map = mutableMapOf<String, MutableList<City>>()
        ALL.forEach { city ->
            if (!map.containsKey(city.province)) order += city.province
            map.getOrPut(city.province) { mutableListOf() } += city
        }
        order.map { it to (map[it] ?: emptyList()) }
    }

    val PROVINCES: List<String> = BY_PROVINCE.map { it.first }

    private val byId: Map<String, City> = ALL.associateBy { it.id }

    fun byId(id: String?): City? = id?.let { byId[it] }

    fun of(province: String, name: String): City? = byId["$province/$name"]

    /** 模糊搜索：城市名 / 省份 / 拼音首字母不做，只做包含匹配（中文输入场景足够）。 */
    fun search(keyword: String): List<City> {
        val q = keyword.trim()
        if (q.isEmpty()) return emptyList()
        return ALL.filter { it.name.contains(q) || it.province.contains(q) }
    }

    /** 自定义城市（表里没有的）：坐标给省份中心，足迹图上按省的位置落点。 */
    fun custom(province: String, name: String): City? {
        if (name.isBlank() || province.isBlank()) return null
        byId["$province/$name"]?.let { return it }
        val anchor = BY_PROVINCE.firstOrNull { it.first == province }?.second?.firstOrNull() ?: return null
        return City(province, name.trim(), anchor.lat, anchor.lon)
    }
